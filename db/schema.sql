-- Schema do agente. Idempotente: pode rodar de novo a cada mudança.
--
-- Fica num schema próprio (`agente`) e não no `public`: o Supabase só expõe o
-- `public` pela API REST, então estas tabelas não ficam acessíveis pela chave
-- anônima do projeto. O único acesso é pela connection string, que só a Vercel tem.

create schema if not exists agente;

-- Histórico da conversa, para o modelo ter contexto das últimas mensagens.
create table if not exists agente.mensagens (
  id          int generated by default as identity primary key,
  papel       text not null check (papel in ('user', 'assistant')),
  conteudo    text not null,
  criado_em   timestamptz not null default now()
);
create index if not exists mensagens_criado_em on agente.mensagens (criado_em desc);

-- Memória de longo prazo: fatos que o dono pediu para guardar.
create table if not exists agente.memorias (
  id          int generated by default as identity primary key,
  texto       text not null,
  criado_em   timestamptz not null default now()
);

-- Lembretes. Estados:
--   pendente  enviado_em is null
--   entregue  enviado_em not null and entregue
--   atrasado  enviado_em not null and not entregue  (a Meta recusou fora da
--             janela de 24h; sai junto com a próxima mensagem do dono)
create table if not exists agente.lembretes (
  id           int generated by default as identity primary key,
  texto        text not null,
  quando       timestamptz not null,
  recorrencia  text check (recorrencia in ('diaria', 'semanal', 'mensal', 'anual')),
  enviado_em   timestamptz,
  entregue     boolean not null default false,
  tentativas   int not null default 0,
  criado_em    timestamptz not null default now()
);
create index if not exists lembretes_pendentes on agente.lembretes (quando) where enviado_em is null;

create table if not exists agente.transacoes (
  id          int generated by default as identity primary key,
  tipo        text not null check (tipo in ('gasto', 'receita')),
  valor       numeric(12, 2) not null check (valor > 0),
  categoria   text not null,
  descricao   text,
  data        date not null default (now() at time zone 'America/Sao_Paulo')::date,
  criado_em   timestamptz not null default now()
);
create index if not exists transacoes_data on agente.transacoes (data);

-- A Meta reentrega o mesmo webhook quando acha que não recebemos. Sem isto
-- um lembrete seria criado duas vezes, um gasto lançado duas vezes.
create table if not exists agente.processadas (
  wamid       text primary key,
  criado_em   timestamptz not null default now()
);

-- URL do endpoint /api/tick e o segredo que o protege. Preenchido pelo
-- scripts/setup-db.js; o pg_cron lê daqui.
create table if not exists agente.config (
  chave  text primary key,
  valor  text not null
);
